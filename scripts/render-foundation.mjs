// Render the installed package's PUBLIC runtime APIs for the static first paint.
// No network downloads, source parsing, copied CSS templates or independent tokens.
import fs from 'node:fs/promises';
import { parseHTML } from 'linkedom';

const { document, window } = parseHTML('<!doctype html><html><head></head><body><div id="accessibility"></div></body></html>');
Object.assign(globalThis, {
  document, window,
  HTMLElement: window.HTMLElement,
  HTMLInputElement: window.HTMLInputElement,
  HTMLTextAreaElement: window.HTMLTextAreaElement,
  HTMLSelectElement: window.HTMLSelectElement,
});
window.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
window.localStorage = { getItem() { return null; }, setItem() {}, removeItem() {} };

const { initDNSFoundation, DNS_FOUNDATION_RUNTIME_VERSION } = await import('@dolomitinordicski/dns-shared-data/foundation');
const { initDNSNavigationStyles } = await import('@dolomitinordicski/dns-shared-data/ui/navigation');
const runtime = initDNSFoundation({
  root: document, language: 'it', persistLanguage: false, shellProfile: 'portal',
  chrome: false, interaction: false, motion: false, semanticMotion: false, print: false,
  dataUI: false, identityUI: false, assetUI: false, capabilityUI: false,
  accessibility: { mountTarget: document.getElementById('accessibility'), settings: { theme: 'light' } },
});
initDNSNavigationStyles({ root: document });
const variables = document.documentElement.getAttribute('style');
const styles = [...document.head.querySelectorAll('style')].map(style => style.textContent);
if (!variables || styles.length < 4) throw new Error('Foundation public runtime did not render its styles');
const css = '/* Generated by installed DNS Foundation ' + DNS_FOUNDATION_RUNTIME_VERSION + ' public APIs. */\n'
  + ':root {' + variables + '}\n' + styles.join('\n');
await fs.mkdir('src/styles/generated', { recursive: true });
await fs.writeFile('src/styles/generated/foundation.css', css);
runtime.disconnect();
console.log('Rendered installed Foundation ' + DNS_FOUNDATION_RUNTIME_VERSION + ' without fetching source files');
